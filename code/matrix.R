rm(list = ls())

A <- rbind(
  c(26, 22, 17, 22, 23),
  c(22, 18, 14, 23, 27),
  c(17, 14, 14, 20, 24),
  c(22, 23, 20, 26, 23),
  c(23, 27, 24, 23, 12)
)

# 1 --------------------------------------------------------------------
det(solve(A)) # 0.0006493506
1 / det(A) # Same value

# 2 --------------------------------------------------------------------
det(A %*% A) # 2371600
det(A)^2 # Same value

# 3 --------------------------------------------------------------------
sum(diag(A)) # 96

# 4 --------------------------------------------------------------------
det(A) # 1540
prod(eigen(A)$values) # Same value
